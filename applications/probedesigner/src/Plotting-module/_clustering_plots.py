def extract_factor_number_from_dataset_name(dataset_name):
    """
    Extract the number of NMF factors from a dataset name.
    
    Examples:
        'Scanpy-Filter_All-Genes_RecoVar_RF_0.25_Dimred_0.75_2factors_100' → 2
        'Xenium-Filter_HVG-Subset_nmf_15factors_200' → 15
        'Scanpy-Filter_All-Genes_Random_100' → None
        
    Parameters:
    -----------
    dataset_name : str
        Full dataset name/path
        
    Returns:
    --------
    int or None
        Number of factors if found, None otherwise
    """
    import re
    
    # Remove path and file extension
    name = os.path.basename(dataset_name)
    if name.endswith('.h5ad'):
        name = name[:-5]
    
    # Look for pattern like _2factors_ or _15factors_
    factor_match = re.search(r'_(\d+)factors_', name)
    if factor_match:
        return int(factor_match.group(1))
    
    return None


def extract_strategy_from_dataset_name(dataset_name):
    """
    Extract the strategy name and gap-filling variant from a dataset filename.
    Factor numbers (_Nfactors_) are removed from the strategy to allow grouping.
    
    Dataset naming pattern:
        {Filter}_{Baseline}_{Strategy}_{N-genes}_{optional-addon}.h5ad
        
    Examples:
        'Scanpy-Filter_All-Genes_deg_only_100_5k-addon' → ('deg_only', None)
        'Scanpy-Filter_All-Genes_RecoVar_PCA_RF_0.5_Dimred_0.5_100' → ('RecoVar_PCA_RF_0.5_Dimred_0.5', None)
        'Scanpy-Filter_All-Genes_RecoVar_RF_0.25_Dimred_0.75_2factors_100' → ('RecoVar_RF_0.25_Dimred_0.75', None)
        'Scanpy-Filter_All-Genes_Random_100' → ('Random', None)
        '/path/to/Scanpy-Filter_All-Genes_deg_only_100_5k-addon_DEG-based-filling.h5ad' → ('deg_only', 'DEG-based-filling')

    Parameters:
    -----------
    dataset_name : str
        Full dataset name/path with optional gap-filling variant suffix

    Returns:
    --------
    tuple : (base_strategy, gap_filling_variant)
        base_strategy: The core strategy identifier (e.g., 'deg_only', 'RecoVar_RF_0.25_Dimred_0.75')
                      Factor numbers are removed from the strategy name.
        gap_filling_variant: One of 'DEG-based-filling', 'global-gene-filling',
                            'cell-type-specific-filling', or None
    """
    import re
    
    # Remove path and file extension
    name = os.path.basename(dataset_name)
    if name.endswith('.h5ad'):
        name = name[:-5]
    
    # Remove factor number from name if present (e.g., _2factors_, _15factors_)
    # This allows factor-range datasets to be grouped by strategy
    name = re.sub(r'_(\d+)factors_', '_', name)
    
    # Check for gap-filling variant - can be at end or before addon suffix
    gap_filling_variant = None
    for variant in ['DEG-based-filling', 'global-gene-filling', 'cell-type-specific-filling']:
        # Check if variant is at the end
        if name.endswith(f'_{variant}'):
            gap_filling_variant = variant
            # Remove variant from name for further parsing
            name = name[:-len(f'_{variant}')]
            break
        # Check if variant appears before an addon suffix (like _mMulti-addon, _5k-addon)
        elif f'_{variant}_' in name:
            gap_filling_variant = variant
            # Remove variant from name (but keep the addon suffix)
            name = name.replace(f'_{variant}_', '_')
            break
    
    # Split by underscores
    parts = name.split('_')
    
    # Strategy identification patterns
    # Format: {Filter}_{Baseline}_{Strategy}_{N-genes}_{optional-addon}
    
    # Common external panels - check these first (but be specific)
    # This function now uses a more generic approach to detect external panels
    # 
    # Strategy:
    # 1. Check for standalone panels (exact match)
    # 2. Check for known external panels that should return simplified names (Spapros, mMulti, 5k)
    # 3. Check if any part of the name matches the pattern of external panels that return full names
    #
    # External panels fall into two categories:
    # Category A: Simple external panels that return a simplified identifier (e.g., 'Spapros', '5k')
    # Category B: Complex external panels that return the full name to preserve filter/size info
    #             These are detected by checking if the name is NOT a standard pipeline pattern
    
    # === CATEGORY A: Simple standalone panels (exact match) ===
    if name == '5k':
        return '5k', gap_filling_variant
    if name == 'mMulti_v1' or name == 'mMulti':
        return 'mMulti_v1', gap_filling_variant
    if name == 'Spapros' or name == 'spapros':
        return 'Spapros', gap_filling_variant
    
    # === CATEGORY A: Known panels in compound names (simplified identifier) ===
    # Check for Spapros - only if it's the strategy, not part of addon
    if 'Spapros' in name and not name.endswith('Spapros-addon'):
        parts_check = name.split('_')
        if len(parts_check) > 2 and 'Spapros' in parts_check[1:3]:
            return 'Spapros', gap_filling_variant
    
    # Check for 5k in compound names (not '5k-addon')
    if '_5k_' in name and not name.endswith('5k-addon'):
        return '5k', gap_filling_variant
    
    # === CATEGORY B: Generic external panel detection ===
    # First check if this contains a known external panel name
    # Do this BEFORE checking pipeline patterns to ensure external panels are detected
    # even if they contain strings like "HVG" in the filter prefix
    known_external_panels = ['NSForest', 'scMER', 'Spapros', 'mMulti_v1', '5k']
    
    for panel_name in known_external_panels:
        # Check if panel name appears in the dataset name
        # Pattern: either as _PanelName_ or ending with _PanelName
        if f'_{panel_name}_' in name or name.endswith(f'_{panel_name}'):
            # Return the simplified panel name for color mapping
            # This allows "Scanpy-Filter_All-Genes_NSForest_100" → 'NSForest'
            # and "Xenium-Filter_HVG-Subset_NSForest_200" → 'NSForest'
            return panel_name, gap_filling_variant
    
    # If no known external panel found, check if this looks like an external panel
    # by checking if it does NOT match standard pipeline patterns
    parts_check = name.split('_')
    
    # Check if name does NOT match any known pipeline patterns
    pipeline_patterns = [
        'RecoVar_RF_', 'RecoVar_PCA_RF_',  # Hybrid RF + dimred strategies
        'RecoVar',  # Bare RecoVar / RecoVar_PCA
        'dimred_only', '_pca_', '_nmf_',  # Dimred-only
        'deg_only', 'rf_simple', 'rf_deg',  # Simple strategies
        'Random', 'HVG', 'random', 'hvg'  # Baselines
    ]

    is_pipeline_pattern = any(pattern in name for pattern in pipeline_patterns)
    is_addon_suffix = name.endswith('-addon')
    
    # If it's not a pipeline pattern and not an addon, and has multiple parts,
    # assume it's a complex external panel - return full name
    if not is_pipeline_pattern and not is_addon_suffix and len(parts_check) >= 3:
        # This catches panels like "Scanpy-Filter_HVG_UnknownTool_200" or any future external panels
        # Return the full name to preserve all context
        return name, gap_filling_variant
    
    # 1. Combination strategies: RF share + dimred share (RecoVar / RecoVar_PCA hybrids).
    # Checked before the simple-strategy string match below so the '_RecoVar_' substring
    # inside a hybrid name is not mistaken for the bare 'RecoVar' strategy.
    combo_pattern = r'RecoVar(_PCA)?_RF_([\d.]+)_Dimred_([\d.]+)'
    combo_match = re.search(combo_pattern, name)
    if combo_match:
        pca_flag, rf_ratio, dimred_ratio = combo_match.groups()
        prefix = 'RecoVar_PCA' if pca_flag else 'RecoVar'
        return f"{prefix}_RF_{rf_ratio}_Dimred_{dimred_ratio}", gap_filling_variant

    # 2. Simple strategies: deg_only, rf_simple, rf_deg, RecoVar(_PCA), hvg, random
    # (these contain underscores, so check as strings). RecoVar_PCA before RecoVar.
    # Also match a LEADING token (name.startswith(f'{strategy}_')) -- some naming
    # conventions (e.g. Analysis-scripts/orchestrators/run_recovar_audit3_validation.sbatch's
    # "RecoVar_raw_rf0.5_nmf0.5_LCA_500genes_seed42") put the strategy first with no
    # underscore before it, so the underscore-bounded check alone would never match.
    simple_strategies = ['deg_only', 'rf_simple', 'rf_deg',
                         'RecoVar_PCA', 'RecoVar', 'hvg', 'random']
    for strategy in simple_strategies:
        if f'_{strategy}_' in name or name.startswith(f'{strategy}_'):
            return strategy, gap_filling_variant

    # 3. Baselines: Random, HVG (check both uppercase and lowercase)
    if 'Random' in parts or 'random' in parts:
        return 'Random', gap_filling_variant
    if 'HVG' in parts or 'hvg' in parts:
        return 'HVG', gap_filling_variant

    # 4. Dimensionality-reduction-only panels. RecoVar emits
    # 'dimred_only_{nmf,pca}_per_celltype'; older Modules_v2 names were
    # '{nmf,pca}_{global,per_celltype}' with an optional trailing _method_a/_method_b.
    # Only the dimred token (nmf / pca) is meaningful now.
    dimred_pattern = r'_(?:dimred_only_)?(pca|nmf)_(?:global|per_celltype)(?:_method_[ab])?'
    dimred_match = re.search(dimred_pattern, name)
    if dimred_match:
        return dimred_match.group(1), gap_filling_variant

    # Fallback: return the dataset name itself if no pattern matches
    return name, gap_filling_variant


def extract_display_name_from_dataset(dataset_name, factor_range_mode=False, include_size=False):
    """
    Extract a clean display name (strategy + filling method) from full dataset name.
    
    This matches the behavior of extract_strategy_and_display_name from the
    variability plotting module - returns short, human-readable strategy names
    without filter/baseline/size/addon information, but INCLUDES the filling method suffix.
    
    Examples:
        'Scanpy-Filter_All-Genes_rf_deg_100_5k-addon' → 'rf_deg'
        'Scanpy-Filter_All-Genes_Random_100' → 'Random'
        'Scanpy-Filter_All-Genes_RecoVar_PCA_RF_0.5_Dimred_0.5_100' → 'RecoVar_PCA 50%'
        'Scanpy-Filter_All-Genes_RecoVar_PCA_RF_0.5_Dimred_0.5_200_DEG-based-filling' → 'RecoVar_PCA 50% (DEG-fill)'
        'Scanpy-Filter_All-Genes_RecoVar_RF_0.5_Dimred_0.5_200_cell-type-specific-filling' → 'RecoVar 50% (CT-fill)'
        'mMulti_v1' → 'mMulti_v1'

    Factor-range mode (factor_range_mode=True):
        'Scanpy-Filter_All-Genes_RecoVar_RF_0.25_Dimred_0.75_2factors_100' → '2-factors'
        'Xenium-Filter_HVG-Subset_dimred_only_nmf_per_celltype_15factors_200' → '15-factors'

    Panel-size mode (include_size=True):
        'Scanpy-Filter_All-Genes_RecoVar_RF_0.75_Dimred_0.25_100_CT-fill' → 'RecoVar 25% (100)'
        'Xenium-Filter_Spapros_200' → 'Spapros (200)'
        
    Parameters:
    -----------
    dataset_name : str
        Full dataset name with settings
    factor_range_mode : bool, optional
        If True, return only the factor number for factor-range plots
    include_size : bool, optional
        If True, include panel size in the display name (for panel-size comparison plots)
        
    Returns:
    --------
    str
        Clean display name for plot labels/legends (includes filling method if present)
    """
    import re
    
    # Extract panel size if requested
    panel_size_str = ""
    if include_size:
        size_match = re.search(r'_(\d+)(?:_|$)', dataset_name)
        if size_match:
            panel_size_str = f" ({size_match.group(1)})"
    
    # If in factor-range mode, return only the factor number
    if factor_range_mode:
        factor_num = extract_factor_number_from_dataset_name(dataset_name)
        if factor_num is not None:
            return f"{factor_num}-factors{panel_size_str}"
    
    # Extract the base strategy and filling variant
    base_strategy, gap_filling_variant = extract_strategy_from_dataset_name(dataset_name)
    
    # Define abbreviations for filling methods
    filling_abbrev = {
        'DEG-based-filling': 'DEG-fill',
        'cell-type-specific-filling': 'CT-fill',
        'global-gene-filling': 'Global-fill'
    }
    
    # For external panels and baselines, return as-is (no filling suffix expected)
    # Known simple external panels (these return simplified names from extract_strategy_from_dataset_name)
    simple_external_panels = ['5k', 'mMulti_v1', 'mMulti', 'Spapros', 'spapros', 'NSForest', 'scMER']
    baselines = ['Random', 'HVG']
    simple_strategies = ['deg_only', 'rf_simple', 'rf_deg', 'nmf', 'pca']
    
    # Check exact match for simple panels/baselines/strategies
    if base_strategy in simple_external_panels or base_strategy in baselines or base_strategy in simple_strategies:
        # For external panels, return just the panel name for clean display
        # This shows "NSForest" or "scMER" instead of the full filename
        return base_strategy + panel_size_str
    
    # Check if this is a complex external panel (full name returned from extract_strategy_from_dataset_name)
    # These panels don't match any pipeline patterns but have multiple components
    # Examples: "Scanpy-Filter_HVG_NSForest_200", "No-Filter_All-Genes_ExternalTool_100"
    pipeline_patterns = [
        'RecoVar_RF_', 'RecoVar_PCA_RF_',  # Hybrid RF + dimred strategies
    ]

    is_pipeline_pattern = any(pattern in base_strategy for pattern in pipeline_patterns)
    has_multiple_parts = len(base_strategy.split('_')) >= 3

    # If it's not a pipeline pattern and has multiple parts, it's likely a complex external panel
    if not is_pipeline_pattern and has_multiple_parts:
        # Return full name for complex external panels to preserve all context
        return base_strategy + panel_size_str

    # For hybrid strategies, extract the dimred percentage.
    # Pattern: RecoVar_RF_0.25_Dimred_0.75 → 'RecoVar 75%'
    #          RecoVar_PCA_RF_0.5_Dimred_0.5 → 'RecoVar_PCA 50%'
    hybrid_pattern = r'RecoVar(_PCA)?_RF_([\d.]+)_Dimred_([\d.]+)'
    hybrid_match = re.search(hybrid_pattern, base_strategy)
    if hybrid_match:
        pca_flag, rf_ratio, dimred_ratio = hybrid_match.groups()
        percentage = int(float(dimred_ratio) * 100)
        prefix = 'RecoVar_PCA' if pca_flag else 'RecoVar'
        display_name = f"{prefix} {percentage}%"

        # Add filling suffix if present
        if gap_filling_variant:
            filling_text = filling_abbrev.get(gap_filling_variant, gap_filling_variant)
            display_name = f"{display_name} ({filling_text})"
        return display_name + panel_size_str
    
    # Fallback: return the base strategy (with filling suffix if present)
    if gap_filling_variant:
        filling_text = filling_abbrev.get(gap_filling_variant, gap_filling_variant)
        return f"{base_strategy} ({filling_text})" + panel_size_str
    return base_strategy + panel_size_str


def resolve_marker_strategy(dataset_names):
    """
    Analyze datasets to determine whether to use gap-filling markers or ratio markers.
    
    Logic:
    - If 2+ gap-filling strategies present with same ratio → use gap-filling markers
    - If 2+ ratio combinations present with same gap-filling → use ratio markers
    - If both vary together → raise error (incompatible grouping)
    - If only one varies → use markers for the varying dimension
    
    Parameters:
    -----------
    dataset_names : list
        List of dataset names to analyze
        
    Returns:
    --------
    str
        One of: 'gap_filling', 'ratio', 'none', or raises ValueError if incompatible
    """
    # Extract info for each dataset
    gap_filling_variants = set()
    ratios = set()
    hybrid_datasets = []
    
    for name in dataset_names:
        base_strategy, gap_filling_variant = extract_strategy_from_dataset_name(name)
        
        # Only analyze hybrid strategies (RecoVar / RecoVar_PCA)
        if base_strategy.startswith('RecoVar_RF_') or base_strategy.startswith('RecoVar_PCA_RF_'):
            # Extract ratio
            import re
            pattern = r'Dimred_([\d.]+)'
            match = re.search(pattern, base_strategy)
            if match:
                ratio = float(match.group(1))
                ratios.add(ratio)
                gap_filling_variants.add(gap_filling_variant)
                hybrid_datasets.append(name)
    
    # If no hybrid strategies, markers don't matter for this distinction
    if not hybrid_datasets:
        return 'none'
    
    num_gap_variants = len(gap_filling_variants)
    num_ratios = len(ratios)
    
    logging.info(f"Marker strategy analysis: {num_gap_variants} gap-filling variants, {num_ratios} ratios")
    logging.info(f"  Gap-filling variants: {gap_filling_variants}")
    logging.info(f"  Ratios: {ratios}")
    
    # Decision logic - Priority: ratios > gap-filling
    if num_ratios >= 2:
        # Multiple ratios - use ratio markers (highest priority)
        logging.info("  → Using ratio markers (multiple ratio combinations - priority)")
        return 'ratio'
    elif num_gap_variants >= 2:
        # Multiple gap-filling strategies, same ratio
        logging.info("  → Using gap-filling markers (multiple gap-filling strategies)")
        return 'gap_filling'
    else:
        # Only one of each - doesn't matter, use ratio markers as default
        logging.info("  → Using ratio markers (default, only one gap-filling variant)")
        return 'ratio'


def generate_panel_size_colors_and_strategy_markers(dataset_names, external_names=None):
    """
    Generate colors based on panel size and markers based on strategy.
    Used when comparing the same strategies across different panel sizes (100, 200, 500).
    
    Color assignment by panel size:
    - 100 genes: Light blue (#87CEEB)
    - 200 genes: Light orange (#FFB366)
    - 500 genes: Dark green (#2E7D32)
    
    Marker assignment by strategy:
    - RecoVar: circle (o) - regardless of filling strategy
    - RecoVar_PCA: circle (o) - regardless of filling strategy
    - nmf: diamond (D)
    - pca: diamond (D)
    - rf_simple: triangle up (^)
    - rf_deg: triangle down (v)
    - deg_only: pentagon (p)
    - hvg: hexagon (h)
    - random: plus (+)
    - Spapros: square (s)
    - Other external panels: star (*)
    
    Parameters:
    -----------
    dataset_names : list
        List of dataset names
    external_names : list, optional
        List of external panel names (e.g., ['Spapros'])
    
    Returns:
    --------
    tuple
        Tuple containing (color_map, marker_map, uses_size_coloring) 
        where uses_size_coloring is True if multiple sizes detected
    """
    import re
    
    color_map = {}
    marker_map = {}
    
    # Define panel size colors
    size_colors = {
        100: "#1C8EBB",  # Blue
        200: "#E77E16",  # Orange
        500: '#2E7D32',  # Dark green (forest green)
    }
    
    # Define strategy markers
    strategy_markers = {
        'RecoVar': 'o',      # Circle
        'RecoVar_PCA': 'o',  # Circle
        'nmf': 'D',         # Diamond
        'pca': 'D',         # Diamond
        'rf_simple': '^',   # Triangle up
        'rf_deg': 'v',      # Triangle down
        'deg_only': 'p',    # Pentagon
        'hvg': 'h',         # Hexagon
        'random': '+',      # Plus
        'Random': '+',      # Plus (capitalized)
        'HVG': 'h',         # Hexagon (capitalized)
        'Spapros': 's',     # Square
        'spapros': 's',     # Square
    }
    
    # External panels not in the list above get a star marker
    external_names = external_names or []
    
    # Extract panel sizes from all datasets
    panel_sizes = {}
    for name in dataset_names:
        # Look for panel size pattern: _100, _200, _500, etc.
        size_match = re.search(r'_(\d+)(?:_|$)', name)
        if size_match:
            panel_size = int(size_match.group(1))
            panel_sizes[name] = panel_size
    
    # Check if we have multiple different panel sizes
    unique_sizes = set(panel_sizes.values())
    uses_size_coloring = len(unique_sizes) > 1
    
    if not uses_size_coloring:
        # Not a multi-size plot, return empty to signal fallback to default coloring
        logging.info("Single panel size detected - not using panel-size-based coloring")
        return {}, {}, False
    
    logging.info(f"Multiple panel sizes detected: {sorted(unique_sizes)}")
    logging.info("Using panel-size-based coloring: 100→light blue, 200→light orange, 500→dark green")
    
    # Assign colors and markers
    for name in dataset_names:
        # Get panel size for color
        panel_size = panel_sizes.get(name)
        if panel_size in size_colors:
            color_map[name] = size_colors[panel_size]
        else:
            # Default color for unknown sizes
            color_map[name] = '#808080'  # Gray
        
        # Get strategy for marker
        base_strategy, gap_filling_variant = extract_strategy_from_dataset_name(name)
        
        # Check if this is an external panel
        is_external = False
        for ext_name in external_names:
            if ext_name.lower() in base_strategy.lower() or base_strategy.lower() in ext_name.lower():
                is_external = True
                if ext_name in strategy_markers or base_strategy in strategy_markers:
                    marker_map[name] = strategy_markers.get(ext_name, strategy_markers.get(base_strategy, '*'))
                else:
                    marker_map[name] = '*'  # Star for unknown external panels
                break
        
        if not is_external:
            # For hybrid strategies (RecoVar, RecoVar_PCA), extract the base type
            if base_strategy.startswith('RecoVar_PCA'):
                marker_map[name] = strategy_markers['RecoVar_PCA']
            elif base_strategy.startswith('RecoVar'):
                marker_map[name] = strategy_markers['RecoVar']
            elif 'nmf' in base_strategy:
                marker_map[name] = strategy_markers['nmf']
            elif 'pca' in base_strategy:
                marker_map[name] = strategy_markers['pca']
            else:
                # Use strategy_markers lookup
                marker_map[name] = strategy_markers.get(base_strategy, 'o')  # Default to circle
        
        logging.info(f"  {name[:50]}... → size={panel_size}, color={color_map[name]}, marker={marker_map[name]}")
    
    return color_map, marker_map, uses_size_coloring


def generate_method_specific_colors_and_markers(dataset_names, external_names=None, group_name=None):
    """
    Generate colors and markers based ONLY on selection strategy (not on settings like filter/baseline/size/addon).
    
    Colors are assigned consistently across all plots based on the strategy used to generate the panel.
    Settings like filter method, baseline gene pool, panel size, and addon panels do NOT affect color.
    
    Marker assignment follows intelligent logic:
    - For hybrid strategies (RecoVar/RecoVar_PCA): Analyzes which dimension varies in the plot
    - If multiple gap-filling strategies → use gap-filling markers (square, diamond, triangle)
    - If multiple ratio combinations → use ratio markers (circle=25%, square=50%, triangle=75%)
    - If both vary → raises error (incompatible grouping)

    Strategy-based color families:
    - Baseline methods: Gray (Random), Yellow (HVG), Orange family (deg_only, rf_simple, rf_deg)
    - RecoVar (RF + NMF) hybrid: Purple family, shade by dimred share
    - RecoVar_PCA (RF + PCA) hybrid: Lime-green family, shade by dimred share
    - Dimred-only: Pink (nmf), Green (pca)
    - External panels: Green family (Spapros, mMulti, 5k)

    Parameters:
    -----------
    dataset_names : list
        List of dataset names (full names with settings)
    external_names : list, optional
        List of external panel names (e.g., ['Spapros', 'mMulti_v1', '5k'])
        These will be assigned custom colors from a gradient
    group_name : str, optional
        Plot group name (retained for signature compatibility; no longer used).

    Returns:
    --------
    tuple
        Tuple containing (color_map, marker_map) dictionaries mapping dataset names to color codes and markers
    """
    
    color_map = {}
    marker_map = {}
    
    # PRIORITY 1: Check if we should use panel-size-based coloring
    # This takes precedence when multiple panel sizes are compared
    size_color_map, size_marker_map, uses_size_coloring = generate_panel_size_colors_and_strategy_markers(
        dataset_names, external_names
    )
    if uses_size_coloring:
        logging.info("Using panel-size-based coloring scheme")
        return size_color_map, size_marker_map
    
    # Check if we're in factor-range mode by examining dataset names
    import re
    factor_range_mode = False
    if dataset_names:
        # Check if any dataset has factor numbers in the name
        factor_range_mode = any(re.search(r'_\d+factors_', name) for name in dataset_names)
    
    # If in factor-range mode, use factor-specific colors
    if factor_range_mode:
        logging.info("Factor-range mode detected: Using factor-specific colors")
        
        # Define a color palette for factors 2-15 (14 colors total)
        # Using a spectral/rainbow gradient that's visually distinct
        factor_colors = {
            2: '#d62728',   # Red
            3: '#ff7f0e',   # Orange
            4: '#ffbb00',   # Golden yellow
            5: '#bcbd22',   # Yellow-green
            6: '#2ca02c',   # Green
            7: '#17becf',   # Cyan
            8: '#1f77b4',   # Blue
            9: '#0000cd',   # Medium blue
            10: '#8b008b',  # Dark magenta
            11: '#9467bd',  # Purple
            12: '#e377c2',  # Pink
            13: '#ff1493',  # Deep pink
            14: '#8b4513',  # Saddle brown
            15: '#696969',  # Dim gray
        }
        
        # All datasets use the same marker (circle) in factor-range mode
        # Color differentiates the factors
        for name in dataset_names:
            factor_num = extract_factor_number_from_dataset_name(name)
            if factor_num is not None and factor_num in factor_colors:
                color_map[name] = factor_colors[factor_num]
                marker_map[name] = 'o'  # All use circle marker
                logging.info(f"  Assigned factor {factor_num} -> color {factor_colors[factor_num]}")
            else:
                # Fallback if factor number not found or out of range
                color_map[name] = '#808080'  # Gray
                marker_map[name] = 'o'
                logging.warning(f"  Could not extract factor number from '{name}'")
        
        return color_map, marker_map
    
    # Normal mode (not factor-range): Continue with strategy-based colors
    
    # Initialize external_names if not provided
    if external_names is None:
        external_names = []
    
    # Define base colors for different method categories - keep these distinct
    # IMPORTANT: Colors are assigned by STRATEGY only, not by dataset settings
    benchmark_colors = {
        # Baseline/control strategies (both uppercase and lowercase)
        'Random': '#808080',         # Gray
        'random': '#808080',         # Gray (lowercase variant)
        'HVG': '#f0dd0d',            # Yellow
        'hvg': '#f0dd0d',            # Yellow (lowercase variant)
        
        # Simple strategies
        'deg_only': "#fa9c4a",       # Orange
        'rf_simple': "#d56a0d",      # Dark orange
        'rf_deg': "#875223",         # Brown
    }

    # Define benchmark markers - all use circles for easy identification
    benchmark_markers = {
        'Random': 'o',           # Circle
        'random': 'o',           # Circle (lowercase variant)
        'HVG': 'o',              # Circle
        'hvg': 'o',              # Circle (lowercase variant)
        'deg_only': 'o',         # Circle
        'rf_simple': 'o',        # Circle
        'rf_deg': 'o',           # Circle
    }

    
    # Default external panel colors (if specific names match)
    # These are for known/common external panels
    # Unknown external panels will get colors from the gradient below
    default_external_colors = {
        'Spapros': "#957d06",
        'spapros': "#957d06",
        '10x_mMulti_v1': '#000000',  # Black - distinct from all other colors
        '10x_5k':'#000000',  # Black - distinct from all other colors
        'mMulti_v1': '#000000',      # Black - distinct from all other colors
        'mMulti': '#000000',  # Black - distinct from all other colors
        '5k': '#000000',  # Black - distinct from all other colors
    }

    # External panels use distinguishable markers
    external_markers = {
        'Spapros': 'o',          # Circle
        'spapros': 'o',          # Circle
        '10x_mMulti_v1': 'o',    # Circle
        '10x_5k': 'o',           # Circle
        'mMulti_v1': 'o',        # Circle
        'mMulti': 'o',
        '5k': 'o',               # Circle
    }

    # Generate gradient colors for additional external panels
    # Purple to teal gradient for external methods
    external_gradient = [
        "#76EFED",
        "#55AFAE",
        "#3E7C7B",
        "#203F3E",
        "#4C8098",
        "#1C4F66",
    ]
     
    # Build external color/marker maps
    external_color_map = {}
    external_marker_map = {}
    
    for idx, ext_name in enumerate(external_names):
        # Check if we have a default color for this external panel
        if ext_name in default_external_colors:
            external_color_map[ext_name] = default_external_colors[ext_name]
        else:
            # Assign from gradient (cycle if more external panels than gradient colors)
            external_color_map[ext_name] = external_gradient[idx % len(external_gradient)]
        
        # Assign marker
        if ext_name in external_markers:
            external_marker_map[ext_name] = external_markers[ext_name]
        else:
            # Alternate between circle and square for unknown external panels
            external_marker_map[ext_name] = 'o' if idx % 2 == 0 else 's'
    
    # Special handling for Spapros: Check if multiple panel sizes (100, 200, 500) are present
    # If so, assign different markers based on panel size to distinguish them
    spapros_datasets = [name for name in dataset_names if 'Spapros' in name or 'spapros' in name]
    spapros_panel_sizes = {}
    
    if len(spapros_datasets) > 1:
        # Extract panel sizes from Spapros dataset names
        import re
        for name in spapros_datasets:
            # Look for panel size pattern: _100, _200, _500, etc.
            size_match = re.search(r'_(\d+)(?:_|$)', name)
            if size_match:
                panel_size = int(size_match.group(1))
                spapros_panel_sizes[name] = panel_size
                logging.info(f"Detected Spapros dataset '{name}' with panel size {panel_size}")
        
        # If we found multiple Spapros with different sizes, assign size-specific markers
        unique_sizes = set(spapros_panel_sizes.values())
        if len(unique_sizes) > 1:
            logging.info(f"Multiple Spapros panel sizes detected: {sorted(unique_sizes)}")
            logging.info("Assigning size-specific markers: 100→circle, 200→square, 500→triangle")
            
            # Define size-to-marker mapping
            size_marker_map = {
                100: 'o',   # Circle for 100 genes
                200: 's',   # Square for 200 genes
                500: '^',   # Triangle for 500 genes
            }
            
            # Update external_marker_map for Spapros datasets based on size
            for name, size in spapros_panel_sizes.items():
                if size in size_marker_map:
                    # Find the external name that matches this dataset
                    for ext_name in external_names:
                        if ext_name in name or name in ext_name or ext_name.lower() == 'spapros':
                            # Store marker with dataset name key for later lookup
                            external_marker_map[name] = size_marker_map[size]
                            logging.info(f"  Assigned marker '{size_marker_map[size]}' to Spapros panel size {size}")
                            break
    
    # Systematic color scheme: Color family = Model type, Shade = dimred share.
    # Color families by model type:
    # - Purple family: RecoVar (hybrid RF + NMF)
    # - Lime-green family: RecoVar_PCA (hybrid RF + PCA)
    # - Pink/Magenta: nmf-only        - Green: pca-only
    # - Orange family: rf_deg and deg-only        - Gray family: baseline methods
    # Within a hybrid family the shade tracks the dimred (NMF/PCA) share: lighter = smaller
    # share, darker = larger share.

    # RecoVar hybrid (RF + NMF) color map, keyed by dimred (NMF) share percentage.
    RecoVar_colors = {
        10: '#DDAAFF',  # Very light purple - 10% NMF
        25: '#BB88FF',  # Light purple - 25% NMF
        50: '#9933FF',  # Vivid purple - 50% NMF
        75: '#7700CC',  # Deep purple - 75% NMF
        90: '#550099',  # Very deep purple - 90% NMF
    }

    # RecoVar_PCA hybrid (RF + PCA) color map, keyed by dimred (PCA) share percentage.
    RecoVar_PCA_colors = {
        10: '#CCFF88',  # Very light lime - 10% PCA
        25: '#AAFF55',  # Light lime - 25% PCA
        50: '#77DD22',  # Vivid lime - 50% PCA
        75: '#55AA00',  # Deep lime green - 75% PCA
        90: '#338800',  # Very deep lime green - 90% PCA
    }

    # Dimred-only color map: DISTINCT from hybrid strategies. One colour per dimred type.
    dimred_only_colors = {
        'nmf': '#cc0066',  # Dark pink
        'pca': '#006600',  # Dark forest green
    }

    # Gap-filling strategy markers
    gap_filling_markers = {
        'DEG-based-filling': 's',                    # Square
        'cell-type-specific-filling': 'D',           # Diamond
        'global-gene-filling': '^',                  # Triangle up
        None: 'o',                                   # Circle (no filling)
    }
    
    # Ratio-specific markers for hybrid strategies (RecoVar, RecoVar_PCA)
    # Based on dimred_ratio (NMF or PCA component share)
    ratio_markers = {
        0.25: 'o',      # Circle - 25% dimred (75% RF)
        0.50: 's',      # Square - 50% dimred (50% RF)
        0.75: '^',      # Triangle - 75% dimred (25% RF)
    }
    
    # Determine marker strategy based on what varies in this plot
    try:
        marker_strategy = resolve_marker_strategy(dataset_names)
        logging.info(f"Resolved marker strategy: {marker_strategy}")
    except ValueError as e:
        # Incompatible grouping detected
        logging.error(str(e))
        raise

        
    # Process each dataset name
    for name in dataset_names:
        # Extract strategy name and gap-filling variant
        base_strategy, gap_filling_variant = extract_strategy_from_dataset_name(name)
        logging.info(f"Processing dataset '{name}' -> base_strategy='{base_strategy}', gap_filling_variant={gap_filling_variant}")
        
        # First check if this is an external panel
        # Match by checking if base_strategy is in the external panel name or vice versa
        is_external = False
        
        # DEBUG: Log external_names list
        logging.info(f"  external_names list has {len(external_names)} items: {external_names}")
        
        for ext_name in external_names:
            # Check both directions: exact match or substring match
            # This handles cases like:
            # - base_strategy='Spapros', ext_name='Spapros'
            # - base_strategy='Spapros', ext_name='Xenium-Filter_Spapros_100_mMulti-addon'
            # - base_strategy='mMulti_v1', ext_name='mMulti_v1'
            logging.info(f"    Checking external_name '{ext_name}' against base_strategy '{base_strategy}'")
            logging.info(f"      base_strategy==ext_name: {base_strategy == ext_name}")
            logging.info(f"      base_strategy in ext_name: {base_strategy in ext_name}")
            logging.info(f"      ext_name in base_strategy: {ext_name in base_strategy}")
            
            if base_strategy == ext_name or base_strategy in ext_name or ext_name in base_strategy:
                color_map[name] = external_color_map.get(ext_name, external_color_map.get(base_strategy, '#808080'))
                # Check if we have a dataset-specific marker (e.g., for Spapros with different sizes)
                # Try: dataset name first, then ext_name, then base_strategy, finally default
                marker_map[name] = external_marker_map.get(name, 
                                   external_marker_map.get(ext_name, 
                                   external_marker_map.get(base_strategy, 'o')))
                is_external = True
                logging.info(f"  ✓ Matched as external via external_names: {ext_name} -> color={color_map[name]}, marker={marker_map[name]}")
                break
        
        # DEBUG: Log check result
        logging.info(f"  After external_names loop: is_external={is_external}")
        
        # Also check if base_strategy directly matches a default external panel
        logging.info(f"  Checking default_external_colors: '{base_strategy}' in dict = {base_strategy in default_external_colors}")
        logging.info(f"  default_external_colors keys: {list(default_external_colors.keys())}")
        
        if not is_external and base_strategy in default_external_colors:
            color_map[name] = default_external_colors[base_strategy]
            # Check if we have a dataset-specific marker (e.g., for Spapros with different sizes)
            marker_map[name] = external_marker_map.get(name, external_markers.get(base_strategy, 'o'))
            is_external = True
            logging.info(f"  ✓ Matched as external via default_external_colors: {base_strategy} -> color={default_external_colors[base_strategy]}, marker={marker_map[name]}")
        
        if is_external:
            logging.info(f"  Continuing (is_external=True, color assigned)")
            continue

        # Check for simple benchmark strategies first
        if base_strategy in benchmark_colors:
            color_map[name] = benchmark_colors[base_strategy]
            # Use gap-filling marker if present, otherwise use benchmark marker
            if gap_filling_variant:
                marker_map[name] = gap_filling_markers.get(gap_filling_variant, 'o')
            else:
                marker_map[name] = benchmark_markers.get(base_strategy, 'o')
            continue

        # Check for hybrid strategies (RecoVar_* or RecoVar_PCA_*)
        if base_strategy.startswith('RecoVar_RF_') or base_strategy.startswith('RecoVar_PCA_RF_'):
            # Pattern: RecoVar(_PCA)?_RF_{rf_ratio}_Dimred_{dimred_ratio}
            dimred_type = 'pca' if base_strategy.startswith('RecoVar_PCA_RF_') else 'nmf'

            dimred_ratio = None
            m = re.search(r'Dimred_([\d.]+)', base_strategy)
            if m:
                try:
                    dimred_ratio = float(m.group(1))
                except ValueError:
                    pass

            # Colour keyed by dimred share percentage only.
            percentage_key = int(round(dimred_ratio * 100)) if dimred_ratio is not None else 50
            color_dict = RecoVar_colors if dimred_type == 'nmf' else RecoVar_PCA_colors
            if percentage_key in color_dict:
                color_map[name] = color_dict[percentage_key]
            else:
                color_map[name] = '#9933FF' if dimred_type == 'nmf' else '#77DD22'
                logging.warning(f"No color defined for {dimred_type} hybrid at {percentage_key}% share")

            # Assign marker based on resolved strategy
            if marker_strategy == 'gap_filling':
                marker_map[name] = gap_filling_markers.get(gap_filling_variant, 'o')
                logging.info(f"  Using gap-filling marker for '{name}': {marker_map[name]}")
            elif marker_strategy == 'ratio':
                if dimred_ratio in ratio_markers:
                    marker_map[name] = ratio_markers[dimred_ratio]
                    logging.info(f"  Using ratio marker for '{name}' (ratio={dimred_ratio}): {marker_map[name]}")
                else:
                    marker_map[name] = 'o'  # Default circle
                    logging.warning(f"  No ratio marker defined for ratio={dimred_ratio}, using circle")
            else:
                # marker_strategy == 'none' or fallback
                if dimred_ratio in ratio_markers:
                    marker_map[name] = ratio_markers[dimred_ratio]
                else:
                    marker_map[name] = gap_filling_markers.get(gap_filling_variant, 'o')
            continue

        # Check for dimred-only strategies (base_strategy is exactly 'nmf' or 'pca')
        if base_strategy in dimred_only_colors:
            color_map[name] = dimred_only_colors[base_strategy]
            # Assign marker based on gap-filling variant
            marker_map[name] = gap_filling_markers.get(gap_filling_variant, 'o')
            continue
            
        # Fallback: check if any benchmark color key is a substring
        matched = False
        for benchmark_key in benchmark_colors.keys():
            if benchmark_key in base_strategy:
                color_map[name] = benchmark_colors[benchmark_key]
                if gap_filling_variant:
                    marker_map[name] = gap_filling_markers.get(gap_filling_variant, 'o')
                else:
                    marker_map[name] = benchmark_markers.get(benchmark_key, 'o')
                matched = True
                break
        
        if matched:
            continue
            
        # Final fallback for unknown patterns - use gray and warn
        logging.warning(f"Unknown strategy pattern: '{base_strategy}' from dataset '{name}' - using default gray")
        logging.warning(f"  Debug: is_external={is_external}, in default_external_colors={base_strategy in default_external_colors}")
        logging.warning(f"  Debug: default_external_colors keys={list(default_external_colors.keys())}")
        color_map[name] = '#808080'  # Gray for unknown
        marker_map[name] = gap_filling_markers.get(gap_filling_variant, 'x')  # X marker for unknown
    
    return color_map, marker_map


