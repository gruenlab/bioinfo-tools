        if batch or gene_set:
            filename_parts.append("filter" if with_filter else "nofilter")
        filename_parts.append(dim_method)
        filename = '_'.join(filename_parts) + '.png'
        
        fig_path = os.path.join(output_dir, filename)
        plt.savefig(fig_path, dpi=PNG_DPI, bbox_inches='tight')
